const TOKEN = /[A-Za-z]+(?:'[A-Za-z]+)*'?/g;

const matchCase = (original: string, fixed: string) => {
  if (original.length > 1 && original === original.toUpperCase()) return fixed.toUpperCase();
  return original[0] === original[0].toUpperCase() ? fixed[0].toUpperCase() + fixed.slice(1) : fixed;
};

export const fixUzbekSpelling = (text: string): string =>
  text
    .replace(TOKEN, (token) => {
      const fixed = WORDS[token.toLowerCase()];
      return fixed ? matchCase(token, fixed) : token;
    })
    .replace(/\bbosh(?= qoldiring)/gi, (match) => (match[0] === 'B' ? "Bo'sh" : "bo'sh"))
    .replace(/yo'qilgan/gi, (match) => (match[0] === 'Y' ? 'Yoqilgan' : 'yoqilgan'));
